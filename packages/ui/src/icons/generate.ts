/**
 * Writes ui's icon components from Lucide's icon data (docs/adr/0005).
 * Development-time only: `scripts/generate-icons.ts` runs it, and a unit test
 * fails when the committed output is stale.
 *
 * Lucide's data comes from a dependency, so it's treated as untrusted. Only
 * the shapes and attributes below, with values matching their grammar, reach
 * the output; anything else stops generation, so a compromised release can't
 * inject markup, styles, links or script into ui.
 */
import type { IconNode } from "./create-icon.js";
import { iconManifest } from "./manifest.js";

const NUMBER = /^-?(?:\d+(?:\.\d+)?|\.\d+)$/;
// Path commands, numbers and separators, nothing else.
const PATH_DATA = /^[MmLlHhVvCcSsQqTtAaZz\d.,\s-]+$/;
const POINTS = /^[\d.,\s-]+$/;
const FILL = /^(?:currentColor|none)$/;

/** Each allowed shape, and the grammar of each attribute it may have. */
const SHAPES: Readonly<Record<string, Readonly<Record<string, RegExp>>>> = {
  path: { d: PATH_DATA },
  circle: { cx: NUMBER, cy: NUMBER, r: NUMBER, fill: FILL },
  rect: { x: NUMBER, y: NUMBER, width: NUMBER, height: NUMBER, rx: NUMBER, ry: NUMBER },
  line: { x1: NUMBER, y1: NUMBER, x2: NUMBER, y2: NUMBER },
  ellipse: { cx: NUMBER, cy: NUMBER, rx: NUMBER, ry: NUMBER },
  polyline: { points: POINTS },
  polygon: { points: POINTS },
};

/**
 * Checks one icon's data against the allowlist and returns it typed, or
 * throws, naming the icon and what was refused.
 */
export function validateIconNode(name: string, data: unknown): IconNode {
  if (!Array.isArray(data) || data.length === 0) {
    throw new Error(`Icon ${name}: expected a non-empty list of shapes.`);
  }
  return data.map((entry: unknown, index) => {
    if (!Array.isArray(entry) || entry.length !== 2) {
      throw new Error(`Icon ${name}, shape ${index}: expected [element, attributes].`);
    }
    const [element, attributes] = entry as [unknown, unknown];
    const grammar = typeof element === "string" ? SHAPES[element] : undefined;
    if (!grammar || !Object.hasOwn(SHAPES, element as string)) {
      throw new Error(
        `Icon ${name}, shape ${index}: the element ${String(element)} isn't allowed.`,
      );
    }
    if (typeof attributes !== "object" || attributes === null || Array.isArray(attributes)) {
      throw new Error(`Icon ${name}, shape ${index}: expected an attribute object.`);
    }
    const checked: Record<string, string> = {};
    for (const [attribute, value] of Object.entries(attributes)) {
      const pattern = Object.hasOwn(grammar, attribute) ? grammar[attribute] : undefined;
      if (!pattern) {
        throw new Error(
          `Icon ${name}, ${String(element)}: the attribute ${attribute} isn't allowed.`,
        );
      }
      if (typeof value !== "string" || !pattern.test(value)) {
        throw new Error(
          `Icon ${name}, ${String(element)}: the value of ${attribute} isn't allowed: ${JSON.stringify(value)}.`,
        );
      }
      checked[attribute] = value;
    }
    return [element, checked] as IconNode[number];
  });
}

/** `rotate-left` becomes `RotateLeftIcon`. */
export function componentName(name: string): string {
  return `${name.replace(/(?:^|-)([a-z0-9])/g, (_, letter: string) => letter.toUpperCase())}Icon`;
}

/**
 * The source of `icons.generated.tsx`, from Lucide's `icon-nodes.json` and
 * the version of `lucide-static` it came from.
 */
export function generateIconsSource(
  nodes: Readonly<Record<string, unknown>>,
  lucideVersion: string,
  manifest: Readonly<
    Record<string, { readonly lucide: string; readonly mirror?: boolean }>
  > = iconManifest,
): string {
  const names = Object.keys(manifest).sort();
  const icons = names.map((name) => {
    const entry = manifest[name] as { readonly lucide: string; readonly mirror?: boolean };
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) {
      throw new Error(`The icon name ${name} isn't kebab-case.`);
    }
    if (!Object.hasOwn(nodes, entry.lucide)) {
      throw new Error(`Icon ${name}: lucide-static has no glyph ${entry.lucide}.`);
    }
    const shapes = validateIconNode(name, nodes[entry.lucide]);
    const mirror = entry.mirror === true;
    const note = mirror ? ", mirrored in right-to-left text" : "";
    return [
      `/**`,
      ` * The \`${name}\` icon: Lucide's \`${entry.lucide}\`${note}.`,
      ` *`,
      ` * @public`,
      ` */`,
      `export function ${componentName(name)}(props: IconProps): ReactElement {`,
      `  return renderIcon(${JSON.stringify(name)}, ${JSON.stringify(shapes)}, ${mirror}, props);`,
      `}`,
    ].join("\n");
  });
  return [
    `/*! Icons from Lucide (https://lucide.dev), ISC licence; those derived from Feather, MIT licence. See THIRD_PARTY_NOTICES.md in @hussmartinez/ui. */`,
    `// Generated by scripts/generate-icons.ts from lucide-static ${lucideVersion} and`,
    `// src/icons/manifest.ts. Don't edit it: change the manifest and run`,
    `// \`pnpm --filter @hussmartinez/ui icons\` (docs/adr/0005).`,
    `import type { ReactElement } from "react";`,
    `import { type IconProps, renderIcon } from "./create-icon.js";`,
    ``,
    `/**`,
    ` * The name of an icon in ui's set, such as \`rotate-left\`. Tools refer to`,
    ` * icons by name (sdk-core ADR 0030), and the SDK maps the names it uses to`,
    ` * their components.`,
    ` *`,
    ` * @public`,
    ` */`,
    `export type IconName =`,
    ...names.map(
      (name, index) => `  | ${JSON.stringify(name)}${index === names.length - 1 ? ";" : ""}`,
    ),
    ``,
    icons.join("\n\n"),
    ``,
  ].join("\n");
}
