import { darkTheme, lightTheme } from "../theme/create-theme.js";
import { renderBlocks, themeBlocks } from "../theme/css-writer.js";
import type { Theme } from "../theme/types.js";
import { baseValues } from "./base.js";
import { type TokenCategory, type TokenName, tokens } from "./definitions.js";
import { tokenDescriptions } from "./descriptions.js";

const HEADER = "Generated by `pnpm --filter @hussmartinez/ui tokens` from src/tokens. Don't edit.";

const BASE_NAMES = new Set(Object.keys(baseValues));

/** The theme without its base tokens, which the built-in CSS declares once. */
function semanticOnly(theme: Theme): Theme {
  const values = Object.fromEntries(
    Object.entries(theme.tokens).filter(([name]) => !BASE_NAMES.has(name)),
  );
  return { ...theme, tokens: values };
}

/** The built-in tokens as CSS, in the `hm.tokens.default` layer. */
function tokensCss(): string {
  const blocks = [
    { selectors: [":root"], values: baseValues },
    ...themeBlocks(":root", semanticOnly(lightTheme), semanticOnly(darkTheme)),
  ];
  return [
    `/* ${HEADER} */`,
    "",
    "/*",
    " * The built-in light and dark themes. Without data-hm-theme, the page",
    " * follows prefers-color-scheme in pure CSS, so nothing flashes (ADR 0007).",
    ' * data-hm-theme="light|dark|system" and data-hm-density="comfortable|compact"',
    " * change any subtree.",
    " */",
    "@layer hm.tokens.default {",
    renderBlocks(blocks, "  "),
    "}",
    "",
  ].join("\n");
}

const CATEGORY_TITLES: Record<TokenCategory, string> = {
  color: "Colour",
  typography: "Typography",
  space: "Space",
  size: "Size",
  shape: "Shape",
  shadow: "Shadow",
  motion: "Motion",
  "z-index": "Z-index",
  opacity: "Opacity",
  focus: "Focus",
};

const code = (value: string | undefined): string =>
  value === undefined ? "" : `\`${value.replaceAll("|", "\\|")}\``;

/** The token reference, as Markdown. */
function tokensMarkdown(): string {
  const lines = [
    "# Token reference",
    "",
    `<!-- ${HEADER} -->`,
    "",
    "Every design token of `@hussmartinez/ui`. Use them in CSS as `var(--hm-<name>)`. Components use only semantic and component tokens; base tokens are the raw scales semantic tokens are built from ([ADR 0006](https://github.com/hussmartinez/sdk-core/blob/main/docs/adr/0006-design-tokens-and-theming.md)).",
    "",
    "Density tokens change with `data-hm-density`: the Light and Dark columns hold their comfortable values. On coarse pointers, `control-height`, `control-height-small` and `target-size` are 44 px in every density.",
    "",
  ];
  const semantic = tokens.filter((definition) => definition.level === "semantic");
  for (const category of Object.keys(CATEGORY_TITLES) as TokenCategory[]) {
    const inCategory = semantic.filter((definition) => definition.category === category);
    if (inCategory.length === 0) {
      continue;
    }
    lines.push(`## ${CATEGORY_TITLES[category]}`, "");
    lines.push("| Token | Light | Dark | Compact | Description |", "|---|---|---|---|---|");
    for (const definition of inCategory) {
      lines.push(
        `| \`--hm-${definition.name}\` | ${code(lightTheme.tokens[definition.name])} | ${code(darkTheme.tokens[definition.name])} | ${code(lightTheme.compact[definition.name])} | ${tokenDescriptions[definition.name as TokenName]} |`,
      );
    }
    lines.push("");
  }
  lines.push(
    "## Component tokens",
    "",
    "Fine-grained overrides for one component. `ui` never declares them: each component reads `var(--hm-<token>, var(--hm-<fallback>))`, so set them on any ancestor, in a theme or in your own CSS.",
    "",
    "| Token | Falls back to | Description |",
    "|---|---|---|",
  );
  for (const definition of tokens.filter((d) => d.level === "component")) {
    lines.push(
      `| \`--hm-${definition.name}\` | \`--hm-${definition.fallback}\` | ${tokenDescriptions[definition.name as TokenName]} |`,
    );
  }
  lines.push("");
  lines.push("## Base tokens", "", "| Token | Value |", "|---|---|");
  for (const definition of tokens.filter((d) => d.level === "base")) {
    lines.push(`| \`--hm-${definition.name}\` | ${code(lightTheme.tokens[definition.name])} |`);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Every generated file, by path relative to the package. The generator
 * script writes them, and a test checks the committed copies are current.
 */
export function generateTokenFiles(): Record<string, string> {
  return {
    "src/tokens/tokens.css": tokensCss(),
    "docs/tokens.md": tokensMarkdown(),
  };
}
